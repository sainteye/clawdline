/** Real Chat interactions driven by synthetic source facts, through an isolated browser. */
import assert from "node:assert/strict"
import {createServer} from "node:http"
import {mkdir,writeFile} from "node:fs/promises"
import {fileURLToPath,pathToFileURL} from "node:url"
import path from "node:path"
import {build} from "esbuild"

const {BOTS_ARTIFACTS:artifacts,PLAYWRIGHT_MODULE:module}=process.env
assert.ok(artifacts&&module)
await mkdir(artifacts,{recursive:true})
const bundle=await build({entryPoints:[fileURLToPath(new URL("./fixtures/project-assistants-conversation-stages.tsx",import.meta.url))],
  bundle:true,write:false,outfile:"stages.js",format:"esm",platform:"browser",target:"es2022",jsx:"automatic",define:{"process.env.NODE_ENV":'"development"'}})
const files=new Map(bundle.outputFiles.map(file=>["/"+path.basename(file.path),file.contents]))
const server=createServer((req,res)=>{
  const body=files.get(req.url)
  if(body){res.setHeader("Content-Type",req.url.endsWith(".css")?"text/css":"text/javascript");res.end(body);return}
  res.setHeader("Content-Type","text/html")
  res.end('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0}</style><link rel="stylesheet" href="/stages.css"><div id="app"></div><script type="module" src="/stages.js"></script>')
})
await new Promise(resolve=>server.listen(0,"127.0.0.1",resolve))
const origin="http://127.0.0.1:"+server.address().port,pw=await import(pathToFileURL(module).href)
const browser=await pw.chromium.launch({headless:true,args:["--disable-features=OmniboxEverywhere"]})
async function verify({width,height,language,reducedMotion}){
  const zh=language!=="en",tag=`${width}-${reducedMotion}`,context=await browser.newContext({viewport:{width,height},hasTouch:width<700,reducedMotion})
  const page=await context.newPage(),facts=[],errors=[]
  page.on("pageerror",error=>errors.push(String(error)))
  await page.route("**/*",route=>route.request().url().startsWith(origin+"/")?route.continue():route.abort())
  const editor=page.locator(".pa-editor textarea"),action=page.locator(".pa-composer .pa-send"),sending=page.locator(".pa-sending")
  const screenshot=state=>page.screenshot({path:path.join(artifacts,tag+"-"+state+".png")})
  const read=(name,arg)=>page.evaluate(([name,arg])=>window.stages[name](...(arg??[])),[name,arg])
  const click=locator=>width<700?locator.tap():locator.click()
  const begin=async text=>{await editor.fill(text);await click(action);await sending.waitFor();await page.waitForFunction(()=>window.stages.sending())}
  const logged=async key=>page.evaluate(key=>window.stages.data[key],key)
  const wait=async fn=>page.waitForFunction(fn,null,{timeout:12000})
  try{
    await page.goto(origin+"/?lang="+language)
    await wait(()=>document.querySelector(".pa-editor textarea:not(:disabled)"))
    assert.equal(await page.locator("[data-arrival]").count(),0)
    await begin("Synthetic staged message")
    await screenshot("sending")
    await read("release",["failed"])
    await wait(()=>document.querySelector(".pa-editor textarea")?.value==="Synthetic staged message")
    await sending.waitFor({state:"detached"})
    assert.equal((await logged("sends")).length,1)
    assert.equal(await page.locator('[data-message-id="person-turn-1"]').count(),0)
    await screenshot("restored")
    await click(action)
    await wait(()=>window.stages.sending());await read("release",["accepted"])
    await page.locator('[data-message-id="person-turn-2"]').waitFor()
    await page.locator('[data-waiting-turn="turn-2"]').waitFor()
    await sending.waitFor({state:"detached"})
    const attempts=await logged("sends")
    assert.equal(attempts.length,2)
    assert.equal(attempts[0].text,attempts[1].text)
    assert.notEqual(attempts[0].command.idempotency_key,attempts[1].command.idempotency_key)
    await read("running",["turn-2"])
    await page.locator(".pa-working").waitFor()
    assert.equal(await action.getAttribute("data-stop"),"true")
    assert.equal(await page.locator('[data-message-id="bot-turn-2"]').count(),0)
    await read("step",["turn-2","agent_thought_chunk","Synthetic tool planning"])
    await page.locator(".pa-working").filter({hasText:zh?"思考中":"Thinking"}).waitFor()
    const trace=page.locator('[data-trace-turn="turn-2"] details')
    await trace.locator("summary").waitFor()
    await screenshot("thinking")
    await click(trace.locator("summary"))
    await read("step",["turn-2","agent_message_chunk","First reported segment"])
    const step=trace.getByRole("button").filter({hasText:zh?"回覆":"Reply"})
    await step.waitFor()
    await click(step)
    await trace.locator(".pa-trace-body").getByText("First reported segment",{exact:true}).waitFor()
    await read("step",["turn-2","agent_message_chunk","First reported segment, continued"])
    await trace.locator(".pa-trace-body").getByText("First reported segment, continued",{exact:true}).waitFor()
    assert.equal(await step.count(),1)
    await screenshot("writing")
    assert.equal(await page.locator('[data-message-id="bot-turn-2"]').count(),0)
    await read("publish",["turn-2","One published synthetic reply"])
    await page.locator('[data-message-id="bot-turn-2"]').waitFor()
    await read("finish",["turn-2"])
    await page.locator(".pa-working").waitFor({state:"detached"})
    const animation=await page.evaluate(()=>window.stages.animations.filter(e=>e.name==="pa-bubble-enter"))
    if(reducedMotion==="reduce")assert.equal(animation.length,0)
    else assert.equal(animation.filter(e=>e.id==="bot-turn-2").length,1)
    assert.equal(animation.filter(e=>e.id==="person-turn-2").length,0,"confirmed user row replayed the optimistic entrance")
    const counts=await page.locator("[data-trace-turn] summary").allTextContents()
    assert.deepEqual(counts.map(label=>Number(label.split(" · ").at(-1))),[1,2])
    facts.push({stage:"delivery",attempts:2,counts,animation})
    await screenshot("completed")

    await begin("Permission and stop fixture");await read("release",["accepted"])
    await page.locator('[data-message-id="person-turn-3"]').waitFor()
    await editor.focus()
    await read("holdDetail")
    await read("offer",["first-approval","turn-3",120000])
    const permission=page.locator('[data-permission-id="first-approval"]')
    await permission.locator("details[open]").waitFor()
    assert.equal(await editor.evaluate(el=>document.activeElement===el),true)
    assert.equal(await permission.locator("[data-option-kind]").count(),0)
    await read("releaseDetail")
    await permission.getByText("synthetic command detail",{exact:true}).waitFor()
    assert.equal((await logged("answers")).length,0)
    if(zh){
      assert.equal(await permission.getByText("在本次對話期間允許",{exact:true}).count(),1)
      assert.equal(await permission.getByText("永遠允許",{exact:true}).count(),1)
    }
    await screenshot("permission")
    await click(permission.locator("summary"));assert.equal(await permission.locator("details[open]").count(),0)
    const info=page.locator(".pa-chat-identity")
    await click(info)
    const refresh=page.locator(".pa-info-panel").getByRole("button",{name:zh?"檢查新訊息":"Check for updates",exact:true})
    await click(refresh)
    await click(page.locator(".pa-info-close"))
    await permission.waitFor();assert.equal(await permission.locator("details[open]").count(),0)
    await page.reload()
    await permission.locator("details[open]").waitFor()
    await permission.getByText("synthetic command detail",{exact:true}).waitFor()
    assert.equal(await page.locator("[data-arrival]").count(),0)
    assert.equal(await trace.locator("summary").textContent(),counts[1])
    const decision=permission.locator('[data-option-kind="allow_always"]').first()
    await decision.evaluate(el=>{el.click();el.click()})
    await wait(()=>window.stages.data.answers.length===1)
    assert.equal((await logged("answers"))[0].option_id,"native-session")
    await permission.waitFor({state:"detached"})
    await read("failDetail",[true])
    await read("offer",["expired-approval","turn-3",9500])
    const expired=page.locator('[data-permission-id="expired-approval"]')
    await expired.getByRole("alert").filter({hasText:"pa_offline"}).waitFor()
    await read("failDetail",[false])
    await click(expired.getByRole("alert").getByRole("button"))
    await expired.locator("[data-option-kind]").first().waitFor()
    await expired.locator('[data-option-kind][disabled]').first().waitFor()
    assert.equal((await logged("answers")).length,1)
    await read("running",["turn-3"])
    await wait(()=>document.querySelector(".pa-send[data-stop]:not(:disabled)"))
    await editor.fill("Draft stays in the composer")
    assert.equal(await action.getAttribute("data-stop"),null)
    assert.equal(await action.getAttribute("type"),"submit")
    await editor.fill("")
    await page.locator('input[type="file"]').setInputFiles({name:"synthetic.png",mimeType:"image/png",
      buffer:Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+dZYQAAAAASUVORK5CYII=","base64")})
    await page.locator(".pa-picture button").waitFor()
    assert.equal(await action.getAttribute("type"),"submit")
    await click(page.locator(".pa-picture button"))
    await begin("Queued synthetic message");await read("release",["accepted"])
    await page.locator(".pa-queued").filter({hasText:"Queued synthetic message"}).waitFor()
    await screenshot("stop")
    const hit=await action.boundingBox()
    if(width<700)assert.ok(hit.width>=44&&hit.height>=44)
    await click(action)
    await wait(()=>window.stages.data.stops.length===1)
    assert.equal((await logged("stops"))[0].turn_id,"turn-3")
    await editor.fill("Draft written while the source stops")
    await read("releaseStop")
    await page.locator(".pa-queued").waitFor({state:"detached"})
    assert.equal(await editor.inputValue(),"Draft written while the source stops")
    facts.push({stage:"permission-and-stop",answers:1,stopTurn:"turn-3",queuedCleared:true,draftKept:true,detailFailureRetried:true,attachmentTogglesSend:true,touchTarget:hit,reload:true})
    assert.deepEqual(errors,[])
    return {tag,facts}
  }catch(error){
    await screenshot("failure").catch(()=>{})
    await writeFile(path.join(artifacts,tag+"-failure.json"),JSON.stringify({error:String(error),facts,errors,body:await page.locator("body").innerText()},null,2))
    throw error
  }finally{await context.close()}
}
try{
  const results=await Promise.allSettled([
    verify({width:1440,height:900,language:"en",reducedMotion:"no-preference"}),
    verify({width:390,height:780,language:"zh-Hant",reducedMotion:"reduce"}),
  ])
  const evidence=results.flatMap(result=>result.status==="fulfilled"?[result.value]:[])
  await writeFile(path.join(artifacts,"conversation-stages.json"),JSON.stringify({evidence,externalModelRequests:0},null,2))
  for(const result of results)if(result.status==="rejected")throw result.reason
  console.log(`PASS ${evidence.length} conversation-stage cases; external model requests=0`)
}finally{
  await browser.close()
  server.closeAllConnections()
  await new Promise(resolve=>server.close(resolve))
}
