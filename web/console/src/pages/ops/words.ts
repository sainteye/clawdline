const words = { en, "zh-Hant": zhHant }

export type OpsWord = keyof typeof words.en

export function opsWord(key: OpsWord, holes: Record<string, string> = {}): string {
  return catalogWord("ops", key).replace(/\{(\w+)\}/g, (all, name) => holes[name] ?? all)
}
