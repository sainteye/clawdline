// renderCloudDecoders is internal/app/cloudops/zz_decode_generated.go: one Go
// decoder for every row of the Cloud vocabulary table whose `decode` is data
// rather than `hand`. Each decoder checks the body's key set against the
// row's shapes, each value against its field's rule, and builds the answer
// identity and the local request the row's route states.
func renderCloudDecoders(ops []cloudvocab.Operation) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/contract-gen from internal/domain/cloudvocab/vocabulary.json; DO NOT EDIT.\n\n")
	b.WriteString("package cloudops\n\n")
	names := []string{}
	for _, o := range ops {
		if o.Decode.Hand == "" {
			names = append(names, o.Op)
		}
	}
	b.WriteString("// generatedDecoders is every word whose decoder the table states.\n")
	b.WriteString("var generatedDecoders = map[string]genDecoder{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "%q: %s,\n", name, decoderName(name))
	}
	b.WriteString("}\n\n")
	b.WriteString("// generatedUnrouted is every generated word whose decode states no local\n")
	b.WriteString("// request: its answer is not a route's, so its op has no route.\n")
	b.WriteString("var generatedUnrouted = map[string]bool{\n")
	for _, o := range ops {
		if o.Decode.Hand == "" && o.Decode.Route == nil {
			fmt.Fprintf(&b, "%q: true,\n", o.Op)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// handDecoded is every word whose decoder stays hand-written, and why.\n")
	b.WriteString("var handDecoded = map[string]string{\n")
	for _, o := range ops {
		if o.Decode.Hand != "" {
			fmt.Fprintf(&b, "%q: %q,\n", o.Op, o.Decode.Hand)
		}
	}
	b.WriteString("}\n")
	for _, o := range ops {
		if o.Decode.Hand != "" {
			continue
		}
		if err := renderDecoder(&b, o); err != nil {
			return nil, fmt.Errorf("%s: %w", o.Op, err)
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated decoders do not format: %w", err)
	}
	return out, nil
}

var decoderWord = regexp.MustCompile(`[a-z0-9]+`)

func decoderName(op string) string {
	out := "genDecode"
	for _, part := range decoderWord.FindAllString(op, -1) {
		out += strings.ToUpper(part[:1]) + part[1:]
	}
	return out
}

func renderDecoder(b *bytes.Buffer, o cloudvocab.Operation) error {
	d := o.Decode
	fmt.Fprintf(b, "\n// %s is the `%s` row's decode.\n", decoderName(o.Op), o.Op)
	if o.Local != nil && o.Local.LocalExemption {
		b.WriteString("//\n// Deliberately this machine (`local_exemption`): its route refuses every\n" +
			"// caller but this machine's own token, which the in-process request carries.\n")
	}
	fmt.Fprintf(b, "func %s(b body) (plan, LocalRequest, bool) {\n", decoderName(o.Op))
	b.WriteString("if !b.hasOneOf(\n")
	for _, s := range o.Shapes {
		keys := append([]string{"type"}, s.Body...)
		fmt.Fprintf(b, "%s,\n", goStrings(keys))
	}
	b.WriteString(") {\nreturn plan{}, LocalRequest{}, false\n}\n")
	fields := sortedKeys(d.Fields)
	for _, field := range fields {
		fmt.Fprintf(b, "if !b.genValid(%q, %s) {\nreturn plan{}, LocalRequest{}, false\n}\n", field, goRule(d.Fields[field]))
	}
	switch d.Reply {
	case cloudvocab.MachineRead:
		b.WriteString("p, ok := machinePlan(b)\n")
	case cloudvocab.SessionRead:
		fmt.Fprintf(b, "p, ok := sessionPlan(b, %s)\n", goTemplate(d.Name))
	case cloudvocab.SessionRequestRead:
		b.WriteString("p, ok := sessionPlan(b, \"\")\n")
		b.WriteString("if ok {\np.request, ok = requestName(b[\"request\"])\np.name = \"read:\" + p.request\n}\n")
	case cloudvocab.MachineAction:
		b.WriteString("p, ok := actionPlan(b, false)\n")
	case cloudvocab.SessionAction:
		b.WriteString("p, ok := actionPlan(b, true)\n")
	default:
		return fmt.Errorf("reply %q", d.Reply)
	}
	b.WriteString("if !ok {\nreturn plan{}, LocalRequest{}, false\n}\n")
	for _, s := range d.AnswerNameSuffixes() {
		fmt.Fprintf(b, "if _, named := b[%q]; named {\np.name += %s\n}\n", s.Field, goTemplate(s.Text))
	}
	for _, field := range fields {
		switch d.Fields[field].Into {
		case cloudvocab.IntoTarget:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.target = genText(v)\n}\n", field)
		case cloudvocab.IntoExecutionGeneration:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.executionGeneration = genText(v)\n}\n", field)
		case cloudvocab.IntoID:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.id = genText(v)\n}\n", field)
		case cloudvocab.IntoParts:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.parts = genText(v)\n}\n", field)
		case cloudvocab.IntoKey:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.key = genText(v)\n}\n", field)
		case cloudvocab.IntoExpect:
			fmt.Fprintf(b, "if v, named := b[%q]; named {\np.expect = genText(v)\n}\n", field)
		case cloudvocab.IntoTyped:
			fmt.Fprintf(b, "if _, named := b[%q]; named {\np.namesTyped = true\n}\n", field)
		case cloudvocab.IntoDocument:
			fmt.Fprintf(b, "if _, named := b[%q]; named {\np.document = b.genObject(%q)\n}\n", field, field)
		}
	}
	if d.Route == nil {
		b.WriteString("return p, LocalRequest{}, true\n}\n")
		return nil
	}
	r := d.Route
	path, err := goPath(r.Path)
	if err != nil {
		return err
	}
	b.WriteString(path)
	fmt.Fprintf(b, "req := LocalRequest{Method: %q, Path: path}\n", o.Local.Method)
	if len(r.Query) > 0 {
		fmt.Fprintf(b, "req.Query = b.genQuery(%s)\n", goValues(r.Query))
	}
	if o.Local.Device || len(r.Headers) > 0 {
		if o.Local.Device {
			b.WriteString("req.Header = asDevice()\n")
		} else {
			b.WriteString("req.Header = map[string]string{}\n")
		}
		for _, name := range sortedKeys(r.Headers) {
			fmt.Fprintf(b, "if v, sent := b.genSource(%s); sent {\nreq.Header[%q] = genText(v)\n}\n", goValue(r.Headers[name]), name)
		}
	}
	if body := r.Body; body != nil {
		switch {
		case body.Empty:
			b.WriteString("req.Body = []byte(\"{}\")\n")
		case body.Object != "":
			fmt.Fprintf(b, "req.Body = b.genObject(%q)\n", body.Object)
		default:
			fmt.Fprintf(b, "req.Body = b.genFields(%s)\n", goValues(body.Fields))
		}
	}
	b.WriteString("return p, req, true\n}\n")
	return nil
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for key := range m {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

func goStrings(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

var placeholder = regexp.MustCompile(`\{(/?)([a-z_]+)([*?]?)\}`)

// goTemplate is a name template as a Go string expression.
func goTemplate(template string) string {
	parts := []string{}
	rest := template
	for {
		at := placeholder.FindStringSubmatchIndex(rest)
		if at == nil {
			if rest != "" {
				parts = append(parts, strconv.Quote(rest))
			}
			break
		}
		if at[0] > 0 {
			parts = append(parts, strconv.Quote(rest[:at[0]]))
		}
		parts = append(parts, fmt.Sprintf("genText(b[%q])", rest[at[4]:at[5]]))
		rest = rest[at[1]:]
	}
	if len(parts) == 0 {
		return `""`
	}
	return strings.Join(parts, " + ")
}

// goPath is the statements that build `path` from a route template: one
// expression, broken only where a segment is optional.
func goPath(template string) (string, error) {
	var b strings.Builder
	terms := []string{}
	declared := false
	flush := func() {
		if len(terms) == 0 {
			return
		}
		op := "+="
		if !declared {
			op, declared = ":=", true
		}
		fmt.Fprintf(&b, "path %s %s\n", op, strings.Join(terms, " + "))
		terms = nil
	}
	rest := template
	for {
		at := placeholder.FindStringSubmatchIndex(rest)
		if at == nil {
			if rest != "" {
				terms = append(terms, strconv.Quote(rest))
			}
			flush()
			return b.String(), nil
		}
		if at[0] > 0 {
			terms = append(terms, strconv.Quote(rest[:at[0]]))
		}
		slash := at[3] > at[2]
		field := rest[at[4]:at[5]]
		mark := rest[at[6]:at[7]]
		switch {
		case slash && mark == "?":
			flush()
			if !declared {
				return "", fmt.Errorf("path %s: an optional segment cannot come first", template)
			}
			fmt.Fprintf(&b, "if t := genText(b[%q]); t != \"\" {\npath += \"/\" + segment(t)\n}\n", field)
		case slash:
			return "", fmt.Errorf("path %s: a {/field} segment must be optional", template)
		case mark == "*":
			terms = append(terms, fmt.Sprintf("escapedDocumentPath(genText(b[%q]))", field))
		case mark == "?":
			return "", fmt.Errorf("path %s: an optional segment carries its slash", template)
		default:
			terms = append(terms, fmt.Sprintf("segment(genText(b[%q]))", field))
		}
		rest = rest[at[1]:]
	}
}

func goValues(values map[string]cloudvocab.Value) string {
	var b strings.Builder
	b.WriteString("map[string]genValue{")
	for _, key := range sortedKeys(values) {
		fmt.Fprintf(&b, "%q: %s, ", key, goValue(values[key]))
	}
	b.WriteString("}")
	return b.String()
}

func goValue(v cloudvocab.Value) string {
	parts := []string{}
	if v.From != "" {
		parts = append(parts, fmt.Sprintf("from: %q", v.From))
	}
	if v.Const != nil {
		parts = append(parts, "constant: "+goLiteral(v.Const))
	}
	if v.Default != nil {
		parts = append(parts, "fallback: "+goLiteral(v.Default))
	}
	if v.OmitEmpty {
		parts = append(parts, "omitEmpty: true")
	}
	if v.Only != "" {
		parts = append(parts, fmt.Sprintf("only: %q", v.Only))
	}
	if v.IfTrue != "" {
		parts = append(parts, fmt.Sprintf("ifTrue: %q", v.IfTrue))
	}
	if v.List {
		parts = append(parts, "list: true")
	}
	return "genValue{" + strings.Join(parts, ", ") + "}"
}

// goLiteral is a table constant as the Go value a decoded body would hold:
// a number stays a json.Number (genNumber), so it encodes as it was written.
func goLiteral(v any) string {
	switch t := v.(type) {
	case string:
		return strconv.Quote(t)
	case bool:
		return strconv.FormatBool(t)
	case json.Number:
		return fmt.Sprintf("genNumber(%q)", t.String())
	}
	panic(fmt.Sprintf("contract-gen: a table constant %v (%T) has no Go spelling", v, v))
}

// checkFuncs is each `cloudvocab.Checks` name and the cloudops function that
// implements it. A name missing here is refused, not skipped.
var checkFuncs = map[string]string{
	"printable":       "printable",
	"request_name":    "genRequestName",
	"session_name":    "genSessionName",
	"task_id":         "isTaskID",
	"fingerprint":     "genFingerprint",
	"generation":      "executionGenerationValid",
	"document_path":   "genDocumentPath",
	"tree_file":       "genTreeFile",
	"tree_directory":  "genTreeDirectory",
	"usage_id":        "genUsageID",
	"verification_id": "genVerificationID",
	"compare_since":   "genCompareSince",
	"work_until":      "genWorkUntil",
	"lower_hex":       "genLowerHex",
	"absolute_path":   "genAbsolutePath",
	"not_blank":       "genNotBlank",
}

func goRule(f cloudvocab.Field) string {
	parts := []string{fmt.Sprintf("kind: %q", string(f.Type))}
	if f.NonEmpty {
		parts = append(parts, "nonEmpty: true")
	}
	if f.MaxBytes > 0 {
		parts = append(parts, fmt.Sprintf("maxBytes: %d", f.MaxBytes))
	}
	if f.Length > 0 {
		parts = append(parts, fmt.Sprintf("length: %d", f.Length))
	}
	if f.Prefix != "" {
		parts = append(parts, fmt.Sprintf("prefix: %q", f.Prefix))
	}
	if f.Min != nil {
		parts = append(parts, fmt.Sprintf("min: genInt(%d)", *f.Min))
	}
	if f.Max != nil {
		parts = append(parts, fmt.Sprintf("max: genInt(%d)", *f.Max))
	}
	if len(f.Enum) > 0 {
		parts = append(parts, "enum: "+goStrings(f.Enum))
	}
	if f.Equals != nil {
		parts = append(parts, fmt.Sprintf("equals: genBool(%v)", *f.Equals))
	}
	if len(f.Checks) > 0 {
		funcs := []string{}
		for _, check := range f.Checks {
			name, ok := checkFuncs[check]
			if !ok {
				panic(fmt.Sprintf("contract-gen: check %q has no cloudops function", check))
			}
			funcs = append(funcs, name)
		}
		parts = append(parts, "checks: []func(string) bool{"+strings.Join(funcs, ", ")+"}")
	}
	if f.Nullable {
		parts = append(parts, "nullable: true")
	}
	if f.SameAs != "" {
		parts = append(parts, fmt.Sprintf("sameAs: %q", f.SameAs))
	}
	if f.Items != nil {
		parts = append(parts, "items: &genRule{"+strings.TrimSuffix(strings.TrimPrefix(goRule(*f.Items), "genRule{"), "}")+"}")
	}
	if f.MinItems != nil {
		parts = append(parts, fmt.Sprintf("minItems: genCount(%d)", *f.MinItems))
	}
	if f.MaxItems != nil {
		parts = append(parts, fmt.Sprintf("maxItems: genCount(%d)", *f.MaxItems))
	}
	if len(f.Properties) > 0 {
		props := []string{}
		for _, key := range sortedKeys(f.Properties) {
			props = append(props, fmt.Sprintf("%q: %s", key, goRule(f.Properties[key])))
		}
		parts = append(parts, "properties: map[string]genRule{"+strings.Join(props, ", ")+"}")
	}
	if len(f.Required) > 0 {
		parts = append(parts, "required: "+goStrings(f.Required))
	}
	if f.Closed {
		parts = append(parts, "closed: true")
	}
	if f.MinKeys > 0 {
		parts = append(parts, fmt.Sprintf("minKeys: %d", f.MinKeys))
	}
	if f.MaxKeys > 0 {
		parts = append(parts, fmt.Sprintf("maxKeys: %d", f.MaxKeys))
	}
	return "genRule{" + strings.Join(parts, ", ") + "}"
}
