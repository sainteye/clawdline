// The web code-shape guard, driven red on the cases it exists for.
import assert from "node:assert/strict"
import { dirname, join } from "node:path"
import { test } from "node:test"
import { fileURLToPath } from "node:url"
import {
  MAX_BRANCHES, MAX_STATEMENTS, functionProblems, importProblem, isGenerated, loadTypeScript, scanSource,
} from "./check-web-code-shape.mjs"

const ts = loadTypeScript(join(dirname(fileURLToPath(import.meta.url)), "..", "web"))
const scan = (webRelative, text) => scanSource(ts, "web/" + webRelative, webRelative, text)

test("core and contract keep to their layer; console may import them", () => {
  assert.match(importProblem("core/src/fleet.ts", "react"), /core imports only itself/)
  assert.match(importProblem("core/src/fleet.ts", "../../console/src/App.tsx"), /reaches outside core/)
  assert.match(importProblem("core/src/fleet.ts", "./theme.css"), /bundler asset/)
  assert.match(importProblem("core/src/fleet.ts", "./words.json?raw"), /bundler asset/)
  assert.match(importProblem("contract/src/index.ts", "@clawdline/core"), /contract imports nothing/)
  assert.equal(importProblem("core/src/fleet.ts", "./client.js"), "")
  assert.equal(importProblem("core/src/fleet.ts", "@clawdline/contract"), "")
  assert.equal(importProblem("console/src/App.tsx", "react"), "")
  assert.equal(importProblem("console/src/App.tsx", "../../core/src/fleet.ts"), "")
})

test("every way to name a module is read, and import.meta is refused in core", () => {
  const { imports } = scan("core/src/x.ts", [
    `import { useState } from "react"`,
    `export { App } from "../../console/src/App.tsx"`,
    `type T = import("react").FC`,
    `const lazy = () => import("react-dom")`,
    `const env = import.meta.env`,
    `import { fleet } from "./fleet.js"`,
  ].join("\n"))
  assert.equal(imports.length, 5, imports.join("\n"))
  assert.ok(imports.some((p) => /web\/core\/src\/x\.ts:5 uses import\.meta/.test(p)))
  assert.deepEqual(scan("console/src/x.ts", `const env = import.meta.env`).imports, [])
})

test("closures count toward their outermost function, and a literal table is not long", () => {
  const handlers = Array.from({ length: MAX_BRANCHES + 1 }, (_, i) => `  const on${i} = () => { if (a) return ${i} }`).join("\n")
  const { functions } = scan("console/src/C.tsx", [
    `export function Panel() {\n${handlers}\n  return <div>{a ? <b/> : null}</div>\n}`,
    `export const table = () => [${Array.from({ length: 1000 }, (_, i) => i).join(", ")}]`,
    `class Store { load() { for (const x of xs) { while (x) {} } } }`,
  ].join("\n"))
  const panel = functions.get("web/console/src/C.tsx\tPanel")
  assert.equal(panel.branches, MAX_BRANCHES + 2)
  assert.equal(functions.has("web/console/src/C.tsx\ton0"), false, "a closure is not measured on its own")
  assert.deepEqual(functions.get("web/console/src/C.tsx\ttable"), { statements: 0, branches: 0 })
  assert.deepEqual(functions.get("web/console/src/C.tsx\tStore.load"), { statements: 2, branches: 2 })
})

test("a new long function, growth, shrinkage and a stale line all fail; tightening only lowers", () => {
  const key = "web/console/src/C.tsx\tPanel"
  const found = new Map([[key, { statements: MAX_STATEMENTS + 10, branches: 5 }], ["web/a.ts\tsmall", { statements: 3, branches: 1 }]])
  const fresh = functionProblems(found, []).problems
  assert.equal(fresh.length, 1)
  assert.match(fresh[0], /Panel has 110 statements/)

  assert.match(functionProblems(found, [`${key}\t${MAX_STATEMENTS + 9}\t5`]).problems.join(), /grew to 110/)

  const { problems, tightened } = functionProblems(found, [`${key}\t${MAX_STATEMENTS + 20}\t9`, "web/a.ts\tsmall\t200\t50", "web/gone.ts\tf\t200\t50"])
  assert.equal(problems.length, 3, problems.join("\n"))
  assert.match(problems.join("\n"), /shrank to 110/)
  assert.match(problems.join("\n"), /now fits the limits/)
  assert.match(problems.join("\n"), /names a function that is gone/)
  assert.deepEqual(tightened, [`${key}\t110\t5`])
})

test("generated files are recognised by their header", () => {
  assert.equal(isGenerated("// Code generated by tools/contract-gen from api/v1. DO NOT EDIT.\n"), true)
  assert.equal(isGenerated("// hand written\n"), false)
})
